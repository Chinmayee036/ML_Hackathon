from pathlib import Path
from collections import Counter

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"


def inspect_split(split):
    split_dir = RAW / split
    trips = sorted(p for p in split_dir.iterdir() if p.is_dir())
    print(f"\n{split}: {len(trips)} trip folders")
    if trips:
        trip = next((p for p in trips if p.name == "00000024"), trips[0])
        print(f"Sample trip: {trip.name}")
        for suffix in (".track", ".nodes", ".arcs", ".route"):
            path = trip / f"{trip.name}{suffix}"
            if path.exists():
                with path.open("r", encoding="utf-8") as f:
                    count = sum(1 for _ in f)
                print(f"  {path.name}: {count:,} rows")


def main():
    inspect_split("train")
    inspect_split("student_test")
    print("\nRaw files inspected. Candidate feature CSVs must be generated by Person 1.")


if __name__ == "__main__":
    main()
